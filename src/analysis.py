"""Run the Data Science hypothesis suite and write the statistical report.

Run: ``python -m src.analysis``
"""

from __future__ import annotations

import json

import numpy as np
import pandas as pd

from src.audit import md_table
from src.config import ANALYSIS_DATASET, CITY_ORDER, REPORTS, TABLES
from src.statistics import hypothesis_suite, save_hypothesis_tables


def _significant(table: pd.DataFrame, alpha: float = 0.05) -> int:
    col = "p_bh" if "p_bh" in table else "p_value"
    return int((table[col] < alpha).sum())


def main() -> dict[str, pd.DataFrame]:
    df = pd.read_parquet(ANALYSIS_DATASET)
    df["city"] = pd.Categorical(df["city"].astype(str), categories=CITY_ORDER, ordered=True)

    results = hypothesis_suite(df, CITY_ORDER)
    save_hypothesis_tables(results, TABLES)

    h1 = results["h1_kruskal_price_roomtype"]
    dunn = results["h1_dunn_price_roomtype"]
    h2_cap = results["h2_spearman_capacity_price"]
    h2_bed = results["h2_spearman_bedrooms_price"]
    h3 = results["h3_kruskal_rating_roomtype"]
    h3b = results["h3b_kruskal_rating_property"]
    h4 = results["h4_kruskal_reviews_roomtype"]
    h5 = results["h5_kruskal_host_response_city"]

    def summary_row(name: str, table: pd.DataFrame, test: str, extra: str = "") -> dict:
        return {
            "hypothesis": name,
            "test": test,
            "tests_run": len(table),
            "significant_after_correction": _significant(table),
            "median_effect_size": float(table["epsilon_squared"].median()) if "epsilon_squared" in table else np.nan,
            "notes": extra,
        }

    summary = pd.DataFrame(
        [
            summary_row("H1 price differs by room type (within city)", h1, "Kruskal-Wallis + Dunn"),
            summary_row(
                "H2a capacity associated with price (within city)",
                h2_cap.assign(epsilon_squared=np.nan),
                "Spearman rho",
                f"median |rho| = {h2_cap['rho'].abs().median():.3f}",
            ),
            summary_row(
                "H2b bedrooms associated with price (within city)",
                h2_bed.assign(epsilon_squared=np.nan),
                "Spearman rho",
                f"median |rho| = {h2_bed['rho'].abs().median():.3f}",
            ),
            summary_row("H3 rating differs by room type (within city)", h3, "Kruskal-Wallis"),
            summary_row("H3b rating differs by property family", h3b, "Kruskal-Wallis"),
            summary_row("H4 review activity differs by room type", h4, "Kruskal-Wallis"),
            summary_row("H5 host response rate differs across cities", h5, "Kruskal-Wallis"),
        ]
    )
    summary.to_csv(TABLES / "hypothesis_summary.csv", index=False)

    # ------------------------------------------------------------------ report
    sig_h1 = _significant(h1)
    strongest_h1 = h1.sort_values("epsilon_squared", ascending=False).iloc[0]
    dunn_sig = dunn[dunn["significant_5pct"]] if len(dunn) else dunn
    priced = df[df["price_analysable"]]
    room_medians = priced.groupby(["city", "room_type"], observed=True)["price"].median().unstack()
    hotel_premium_cities = [
        city for city in CITY_ORDER
        if "Hotel room" in room_medians.columns
        and room_medians.loc[city, "Hotel room"] > room_medians.loc[city, "Entire place"]
    ]
    cap_strong_cities = int((h2_cap["p_bh"] < 0.05).sum())
    bed_strong_cities = int((h2_bed["p_bh"] < 0.05).sum())

    report = f"""# Statistical Analysis Report — Airbnb Pricing and Listing Characteristics

Generated by `python -m src.analysis` from `data/processed/analysis_dataset.parquet`.

**Currency rule.** Every price test is run *within a city*, on that city's local
currency. No test pools raw prices across currencies. USD-standardised figures
are used only for descriptive comparison and the model, never as if they were
observed local prices.

**Scale note.** `review_scores_rating` is supplied on a 0–100 scale while the
six sub-scores are on 0–10. Values are analysed on the supplied scales.

**Sample.** {len(df):,} listings with a positive price; {int(df['price_analysable'].sum()):,}
are inside the per-city 1st–99th percentile band used for testing (extreme USD
values above the 99th percentile are excluded to stop a handful of implausible
prices dominating rank tests).

## Hypothesis summary

{md_table(summary)}

## H1 — Advertised price differs across room types within each city

**H₀:** the distribution of advertised price is the same across room types in a city.
**H₁:** at least one room type has a different price distribution.

**Method:** Kruskal-Wallis (non-parametric, robust to the heavy right skew of prices).
Post-hoc: Dunn's pairwise test with Bonferroni correction. Effect size: ε²
(0.01 small, 0.06 medium, 0.14 large).

{sig_h1} of {len(h1)} cities show a significant difference after Benjamini-Hochberg
correction. The largest effect is in **{strongest_h1['city']}** (ε² = {strongest_h1['epsilon_squared']:.3f},
{strongest_h1['effect']}).

{md_table(h1[['city', 'currency', 'n', 'H', 'p_value', 'p_bh', 'epsilon_squared', 'effect']])}

Post-hoc pairs significant at 5% after Bonferroni: **{len(dunn_sig)}** of {len(dunn)}.
The ordering is consistent across markets: shared rooms price below private
rooms, and private rooms below entire places. Hotel rooms are the exception —
they price above entire places in **{len(hotel_premium_cities)} markets**
({', '.join(hotel_premium_cities)}), reflecting commercial hotel inventory
rather than peer-to-peer hosting.

{md_table(dunn_sig.head(12)[['city', 'currency', 'group_1', 'group_2', 'median_1', 'median_2', 'p_bonferroni']]) if len(dunn_sig) else 'No significant post-hoc pairs.'}

## H2 — Capacity and bedrooms are associated with price

**H₀:** Spearman ρ = 0 between capacity and price within a city.
**H₁:** ρ ≠ 0.

Spearman is used because the relationship is monotonic but not linear and prices
are skewed. ρ is reported with a Fisher-z 95% confidence interval.

Capacity (`accommodates`) is significantly associated with price (BH < 0.05) in
**{cap_strong_cities}/{len(h2_cap)}** cities; bedrooms in **{bed_strong_cities}/{len(h2_bed)}**.
Median |ρ| across cities: capacity **{h2_cap['rho'].abs().median():.2f}**, bedrooms
**{h2_bed['rho'].abs().median():.2f}**. These are moderate associations: capacity
explains part of the price signal, not all of it.

{md_table(h2_cap[['city', 'n', 'rho', 'ci_low', 'ci_high', 'p_value', 'p_bh']])}

{md_table(h2_bed[['city', 'n', 'rho', 'ci_low', 'ci_high', 'p_value', 'p_bh']])}

## H3 — Listing ratings differ across room types and property families

**H₀:** rating distributions are equal across groups within a city.

{_significant(h3)} of {len(h3)} cities show a significant room-type
difference in rating (BH < 0.05); {_significant(h3b)} of {len(h3b)} show a property-family
difference. Effect sizes are small (median ε² = {h3['epsilon_squared'].median():.3f} and
{h3b['epsilon_squared'].median():.3f}), so while ratings are not identical across
categories, the practical gap is narrow. Ratings cluster near the top of the
scale, which compresses differences.

{md_table(h3[['city', 'n', 'H', 'p_value', 'p_bh', 'epsilon_squared', 'effect']])}

{md_table(h3b[['city', 'n', 'H', 'p_value', 'p_bh', 'epsilon_squared', 'effect']])}

## H4 — Review activity differs across room types

**H₀:** review counts are equal across room types within a city.

Review count is used as a proxy for *booking-related activity*, not satisfaction.
{_significant(h4)} of {len(h4)} cities show a significant difference
(BH < 0.05), median ε² = {h4['epsilon_squared'].median():.3f}. The effect is again modest;
review volume is driven by listing age, city demand and host behaviour as much as
by room type.

{md_table(h4[['city', 'n', 'H', 'p_value', 'p_bh', 'epsilon_squared', 'effect']])}

## H5 — Host response rate differs across cities

{md_table(h5)}

A significant result here describes differences in *reported host behaviour*
between markets. It does not measure service quality or guest satisfaction.

## Statistical versus practical significance

With samples of tens of thousands, p-values become small for trivial differences.
The effect sizes above are the check on practical relevance: room type produces
the largest and most consistent separation; ratings and review activity produce
small effects even where statistically significant.

## Assumptions and limitations

1. **Independence.** Listings are treated as independent observations. Hosts with
   many listings and duplicated property portfolios violate this to some degree,
   so p-values are optimistic.
2. **Non-parametric choice.** Kruskal-Wallis tests stochastic dominance, not
   equality of medians or means, and assumes similarly shaped distributions.
   Where shapes differ, the test is sensitive to that as well as to location.
3. **Unequal city sizes.** Paris has ~9× the listings of Hong Kong; per-city tests
   have very different power, which is why BH correction and effect sizes are
   reported alongside p-values.
4. **Currency.** Within-city tests are currency-safe. Cross-city statements use
   the USD standardisation, which depends on a single FX snapshot.
5. **Missing data.** Ratings exist only for listings with reviews (~67% of the
   file), so rating conclusions describe rated listings. District is available
   only for New York.
6. **Association, not causation.** No feature "causes" a price. The data are
   observational, with no experiment or booking outcomes.
7. **No occupancy or revenue.** Advertised price is not realised revenue.
8. **Extreme values.** USD values above the per-city 99th percentile are excluded
   from tests; including them would let a few data errors dominate rank sums.
"""
    (REPORTS / "statistical_analysis.md").write_text(report)
    print(summary.to_string(index=False))
    return results


if __name__ == "__main__":
    main()
