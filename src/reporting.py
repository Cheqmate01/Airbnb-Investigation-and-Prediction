"""Markdown report generation from saved analysis artifacts.

Run: ``python -m src.reporting``
"""

from __future__ import annotations

import json

import pandas as pd

from src.audit import md_table
from src.config import MODELS, REPORTS, TABLES


def write_model_report() -> str:
    comparison = pd.read_csv(TABLES / "model_comparison.csv")
    by_city = pd.read_csv(TABLES / "model_metrics_by_city.csv")
    cv = pd.read_csv(TABLES / "model_cross_validation.csv")
    err_city = pd.read_csv(TABLES / "model_error_by_city.csv")
    err_band = pd.read_csv(TABLES / "model_error_by_price_band.csv")
    importance = pd.read_csv(TABLES / "feature_importance_permutation.csv")
    metadata = json.loads((MODELS / "model_metadata.json").read_text())

    best = metadata["model_family"]
    best_row = comparison.set_index("model").loc[best]
    baseline_mae = metadata["city_median_baseline_MAE_usd"]
    reduction = metadata["mae_reduction_vs_city_median_pct"]
    best_city = by_city[by_city["model"] == best].sort_values("MAE_usd")

    report = f"""# Price Prediction Model — Evaluation Report

Generated by `python -m src.modelling` and `python -m src.reporting`.

## 1. Prediction problem

Estimate the **advertised nightly price** of an Airbnb listing from attributes
that are observable when the listing is created. The output is a price
*estimate*, not a revenue forecast, occupancy estimate or pricing instruction.

**Target:** `price_usd` = local advertised price × documented USD rate
(ECB snapshot {metadata['currency_assumption'].split('snapshot ')[-1]}).
Models are trained on `log1p(price_usd)` to stabilise the heavy right skew and
evaluated after transforming predictions back to USD.

**Why one standardised model instead of ten local-currency models:** the
assignment permits either approach. A single USD model pools {metadata['n_training_rows']:,}
training listings, learns a shared price structure and still receives `city` as
a feature so market level differences are captured. The trade-off is dependence
on one FX snapshot, which is stated as a limitation in §8.

## 2. Data preparation and leakage control

- Only rows with a positive price inside the per-city 1st–99th percentile band
  are modelled. Non-positive prices and implausible upper-tail values are
  documented in the data-quality report and excluded.
- **CORE feature set** (deployable): city, room type, property family, capacity,
  bedrooms (plus missing flag), stay policy, amenities and host profile.
- **EXTENDED feature set** (sensitivity analysis): everything in CORE plus review
  counts, review recency and the seven listing-level rating scores. These are
  unavailable for a brand-new listing and are therefore not used for the
  deployed model.
- Review-derived and target-derived fields are excluded from CORE. In particular
  no city price average, review score or review count enters the deployable
  feature set.
- Numeric features: median imputation. Categorical features: one-hot (linear,
  forest) or native categorical handling (gradient boosting).

## 3. Split and baseline

- 80/20 stratified split by city, `random_state = 42` ({metadata['n_training_rows']:,} train / {metadata['n_test_rows']:,} test).
- Baseline 1: global median price.
- Baseline 2: **per-city median price** — the stronger, fairer baseline.
- A 3-fold stratified cross-validation on the training set checks that the
  holdout result is not a split artefact.

The estimator must beat the per-city median baseline to be useful: that baseline
already captures the market-level price level, so improvement has to come from
property and host characteristics.

## 4. Model comparison (held-out test set, USD)

{md_table(comparison)}

**Best deployable model:** `{best}`. Test MAE **${best_row['MAE_usd']:,.2f}**, RMSE
**${best_row['RMSE_usd']:,.2f}**, R² **{best_row['R2']:.3f}**, median absolute percentage
error **{best_row['median_abs_pct_error']:.1f}%**. This is a **{reduction:.1f}%** reduction in MAE
versus the per-city median baseline (${baseline_mae:,.2f}).

**Selection rule (fixed before comparison):** models within 1% of the best
held-out MAE are treated as tied, because a sub-1% difference is not
practically meaningful. Ties break on R², then MAE, then training time. This
prevents a model that is marginally better on one metric but far more expensive
to train and larger to ship from being deployed by accident.

Cross-validation:

{md_table(cv)}

## 5. Error analysis

### By city

{md_table(err_city)}

### By price band

{md_table(err_band)}

Errors scale with price: expensive listings are harder to predict in absolute
USD, while percentage error is usually highest in the cheapest band, where small
absolute differences become large percentages. City-level MAE differences partly
reflect genuine price dispersion (New York and Paris have wide markets) and
partly the unequal number of observations per city.

### Largest errors

The 25 largest percentage errors are saved to
`outputs/tables/model_largest_errors.csv`. They are dominated by listings whose
advertised price is far outside the typical band for their stated characteristics
— exactly the cases where an advertised price may reflect a data-entry issue, a
luxury/unusual property, or a monthly rather than nightly rate.

## 6. Feature importance

Permutation importance on the held-out set (increase in MAE when a feature is
shuffled):

{md_table(importance.head(15))}

Interpretation: the market itself (`city`) dominates, followed by capacity
(`bedrooms`, `accommodates`), fine-grained location (longitude/latitude) and
room category. The result is consistent with the statistical findings in
`reports/statistical_analysis.md`, which is useful triangulation: two
independent methods identify the same drivers.

## 7. Overfitting, underfitting and model choice

The gap between training and test metrics is reported in the comparison table.
A large gap indicates overfitting (the forest is the most exposed to this); a
small gap with poor absolute accuracy indicates underfitting (the ridge model
is the clearest example, because the price surface is non-linear). Gradient
boosting is selected because it captures non-linearities and interactions while
retaining a modest train/test gap.

## 8. Limitations

- Advertised price ≠ revenue, occupancy or profit. Nothing here predicts demand.
- USD conversion uses a single ECB snapshot; a different date would shift every
  cross-city number and the target scale.
- The model is trained on supplied listings, which are not a random sample of
  the market; hosts self-select into Airbnb and into the extract.
- CORE excludes review history for leakage reasons. For mature listings, the
  EXTENDED model is more accurate but less deployable.
- No bathrooms field exists, and `bedrooms` is missing for ~10% of listings.
- Extreme advertised prices are excluded from training, so the model is
  deliberately conservative at the top of the market.
- Association is not causation: feature importance describes predictive
  contribution, not the causal effect of, for example, adding a bedroom.

## 9. How the model is used

```bash
.venv/bin/python -c "from src.inference import predict_price; print(predict_price({{'city':'Rome','room_type':'Entire place','accommodates':4,'bedrooms':2}}))"
```

The packaged artifact is `outputs/models/price_model_core.joblib`; metadata,
feature list and metrics are in `outputs/models/model_metadata.json`.
"""
    (REPORTS / "model_report.md").write_text(report)
    return report


if __name__ == "__main__":
    path = REPORTS / "model_report.md"
    write_model_report()
    print(f"Wrote {path}")
